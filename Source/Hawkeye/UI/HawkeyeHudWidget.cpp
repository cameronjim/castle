void UHawkeyeHudWidget::NativeTick(const FGeometry& MyGeometry, float DeltaSeconds)
{
	Super::NativeTick(MyGeometry, DeltaSeconds);

	PollPawnReticleState();
	PollPawnDrawState(MyGeometry);
	UpdateGrappleMarker();
	RefreshMovementDebug();
	UpdatePartnerWidgets(DeltaSeconds);
	UpdatePhoneBadge();
	UpdateComboCounter();

	if (HitFlashRemaining > 0.f)
	{
		HitFlashRemaining -= DeltaSeconds;
		if (HitFlashRemaining <= 0.f)
		{
			HitFlashRemaining = 0.f;
			RefreshReticle();
			RefreshDrawIndicator();
		}
	}
}

void UHawkeyeHudWidget::HandleWeaponHit(AActor* /*HitActor*/, float /*DamageDealt*/)
{
	FlashHitMarker();
}

void UHawkeyeHudWidget::NativeConstruct()
{
	Super::NativeConstruct();

	if (MissionCompleteText.IsEmpty())
	{
		MissionCompleteText = NSLOCTEXT("Hawkeye", "MissionComplete", "Mission complete");
	}
	if (GrappleHintText.IsEmpty())
	{
		GrappleHintText = NSLOCTEXT("Hawkeye", "GrappleHint", "Q");
	}
	if (GrappleNoArrowsText.IsEmpty())
	{
		GrappleNoArrowsText = NSLOCTEXT("Hawkeye", "GrappleNoArrows", "No grapple arrows");
	}

	BindToGame();
	RefreshObjective();
	RefreshAmmo();
	ClearPrompt();
	ApplySettings(UHawkeyeSettingsSubsystem::GetCurrentSettings(this));
}

void UHawkeyeHudWidget::NativeDestruct()
{
	UnbindFromGame();

	Super::NativeDestruct();
}

void UHawkeyeHudWidget::BindToGame()
{
	if (bBound)
	{
		return;
	}

	if (UMissionSubsystem* Missions = UMissionSubsystem::Get(this))
	{
		Missions->OnMissionStarted.AddDynamic(this, &UHawkeyeHudWidget::HandleMissionStarted);
		Missions->OnObjectiveUpdated.AddDynamic(this, &UHawkeyeHudWidget::HandleObjectiveUpdated);
		Missions->OnMissionComplete.AddDynamic(this, &UHawkeyeHudWidget::HandleMissionComplete);
	}

	if (UWeaponComponent* Weapon = FindPawnWeapon())
	{
		Weapon->OnAmmoChanged.AddDynamic(this, &UHawkeyeHudWidget::HandleAmmoChanged);
		Weapon->OnHit.AddDynamic(this, &UHawkeyeHudWidget::HandleWeaponHit);
		BoundWeapon = Weapon;
	}

	const APlayerController* PC = GetOwningPlayer();
	const APawn* Pawn = PC ? PC->GetPawn() : nullptr;
	if (UTakedownComponent* Takedown = Pawn ? Pawn->FindComponentByClass<UTakedownComponent>() : nullptr)
	{
		Takedown->OnTakedownPerformed.AddDynamic(this, &UHawkeyeHudWidget::HandleTakedownPerformed);
		BoundTakedown = Takedown;
	}

	if (UHawkeyeSettingsSubsystem* Settings = UHawkeyeSettingsSubsystem::Get(this))
	{
		Settings->OnSettingsChanged.AddUniqueDynamic(this, &UHawkeyeHudWidget::HandleSettingsChanged);
	}

	bBound = true;
}

void UHawkeyeHudWidget::UnbindFromGame()
{
	if (!bBound)
	{
		return;
	}

	if (UMissionSubsystem* Missions = UMissionSubsystem::Get(this))
	{
		Missions->OnMissionStarted.RemoveDynamic(this, &UHawkeyeHudWidget::HandleMissionStarted);
		Missions->OnObjectiveUpdated.RemoveDynamic(this, &UHawkeyeHudWidget::HandleObjectiveUpdated);
		Missions->OnMissionComplete.RemoveDynamic(this, &UHawkeyeHudWidget::HandleMissionComplete);
	}

	if (BoundWeapon)
	{
		BoundWeapon->OnAmmoChanged.RemoveDynamic(this, &UHawkeyeHudWidget::HandleAmmoChanged);
		BoundWeapon->OnHit.RemoveDynamic(this, &UHawkeyeHudWidget::HandleWeaponHit);
		BoundWeapon = nullptr;
	}
	if (BoundBow)
	{
		BoundBow->OnHit.RemoveDynamic(this, &UHawkeyeHudWidget::HandleBowHit);
		BoundBow = nullptr;
	}

	if (BoundTakedown)
	{
		BoundTakedown->OnTakedownPerformed.RemoveDynamic(this, &UHawkeyeHudWidget::HandleTakedownPerformed);
		BoundTakedown = nullptr;
	}

	if (UHawkeyeSettingsSubsystem* Settings = UHawkeyeSettingsSubsystem::Get(this))
	{
		Settings->OnSettingsChanged.RemoveDynamic(this, &UHawkeyeHudWidget::HandleSettingsChanged);
	}

	bBound = false;
}

UWeaponComponent* UHawkeyeHudWidget::FindPawnWeapon() const
{
	const APlayerController* PC = GetOwningPlayer();
	const APawn* Pawn = PC ? PC->GetPawn() : nullptr;
	return Pawn ? Pawn->FindComponentByClass<UWeaponComponent>() : nullptr;
}

FText UHawkeyeHudWidget::FormatAmmo(int32 Magazine, int32 Reserve)
{
	return FText::FromString(FString::Printf(TEXT("%d / %d"), Magazine, Reserve));
}

FText UHawkeyeHudWidget::BuildObjectiveText() const
{
	const UMissionSubsystem* Missions = UMissionSubsystem::Get(this);
	if (!Missions)
	{
		return FText::GetEmpty();
	}

	const UMissionDefinition* Mission = Missions->GetCurrentMission();
	if (!Mission || !Mission->bShowObjectiveText)
	{
		return FText::GetEmpty();
	}

	if (const UMissionObjective* Objective = Missions->GetCurrentObjective())
	{
		// The hint goes on its own line under the title.
		return Objective->Hint.IsEmpty() ? Objective->Title
			: FText::Format(NSLOCTEXT("Hawkeye", "ObjectiveWithHint", "{0}\n{1}"), Objective->Title, Objective->Hint);
	}

	return Missions->IsMissionComplete() ? MissionCompleteText : FText::GetEmpty();
}

void UHawkeyeHudWidget::RefreshObjective()
{
	if (ObjectiveText)
	{
		ObjectiveText->SetText(BuildObjectiveText());
	}
}

void UHawkeyeHudWidget::RefreshAmmo()
{
	// The pawn can gain a weapon component (or have it enabled) partway through the level.
	UWeaponComponent* Weapon = FindPawnWeapon();
	if (Weapon && Weapon != BoundWeapon)
	{
		if (BoundWeapon)
		{
			BoundWeapon->OnAmmoChanged.RemoveDynamic(this, &UHawkeyeHudWidget::HandleAmmoChanged);
			BoundWeapon->OnHit.RemoveDynamic(this, &UHawkeyeHudWidget::HandleWeaponHit);
		}
		Weapon->OnAmmoChanged.AddDynamic(this, &UHawkeyeHudWidget::HandleAmmoChanged);
		Weapon->OnHit.AddDynamic(this, &UHawkeyeHudWidget::HandleWeaponHit);
		BoundWeapon = Weapon;
	}

	if (!AmmoText)
	{
		return;
	}

	if (!Weapon || !Weapon->HasWeapon())
	{
		AmmoText->SetText(FText::GetEmpty());
		return;
	}

	AmmoText->SetText(FormatAmmo(Weapon->CurrentAmmo, Weapon->ReserveAmmo));
}

void UHawkeyeHudWidget::SetPrompt(FText Prompt)
{
	CurrentPrompt = ApplyGamepadHint(Prompt);
	if (PromptText)
	{
		PromptText->SetText(CurrentPrompt);
	}
}

FText UHawkeyeHudWidget::ApplyGamepadHint(FText KeyboardHint) const
{
	const AHawkeyePlayerController* PC = Cast<AHawkeyePlayerController>(GetOwningPlayer());
	if (!PC || !PC->IsUsingGamepad() || KeyboardHint.IsEmpty())
	{
		return KeyboardHint;
	}

	FString Text = KeyboardHint.ToString();
	if (Text.Equals(TEXT("Q")))
	{
		// The grapple marker's bare "Q" hint; RB fires IA_Grapple on a gamepad.
		return NSLOCTEXT("Hawkeye", "GrappleHintGamepad", "RB");
	}

	// Takedown and interact share the Y face button; both prompts read the same on a pad.
	Text.ReplaceInline(TEXT("[F]"), TEXT("[Y]"));
	Text.ReplaceInline(TEXT("[E]"), TEXT("[Y]"));
	return FText::FromString(Text);
}

