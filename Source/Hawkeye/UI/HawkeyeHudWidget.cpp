TSharedRef<SWidget> UHawkeyeHudWidget::RebuildWidget()
{
	// WBP_Hud is generated by a script and has no designer layout, so build the four driven
	// widgets here when nothing is bound.
	if (WidgetTree && !WidgetTree->RootWidget)
	{
		UOverlay* Root = WidgetTree->ConstructWidget<UOverlay>(UOverlay::StaticClass(), TEXT("HudRoot"));
		WidgetTree->RootWidget = Root;

		auto AddText = [this, Root](TObjectPtr<UTextBlock>& TextSlot, const TCHAR* Name,
			EHorizontalAlignment HAlign, EVerticalAlignment VAlign, const FMargin& TextPadding)
		{
			if (!TextSlot)
			{
				TextSlot = WidgetTree->ConstructWidget<UTextBlock>(UTextBlock::StaticClass(), Name);
			}
			if (UOverlaySlot* OverlaySlot = Cast<UOverlaySlot>(Root->AddChild(TextSlot)))
			{
				OverlaySlot->SetHorizontalAlignment(HAlign);
				OverlaySlot->SetVerticalAlignment(VAlign);
				OverlaySlot->SetPadding(TextPadding);
			}
		};

		AddText(ObjectiveText, TEXT("ObjectiveText"), HAlign_Left, VAlign_Top, FMargin(48.f, 48.f, 0.f, 0.f));
		AddText(AmmoText, TEXT("AmmoText"), HAlign_Right, VAlign_Bottom, FMargin(0.f, 0.f, 48.f, 48.f));
		AddText(PromptText, TEXT("PromptText"), HAlign_Center, VAlign_Center, FMargin(0.f, 120.f, 0.f, 0.f));
		AddText(DebugText, TEXT("DebugText"), HAlign_Left, VAlign_Top, FMargin(48.f, 80.f, 0.f, 0.f));
		DebugText->SetVisibility(ESlateVisibility::Collapsed);

		BuildReticle(Root);
		BuildGrappleMarker(Root);
		BuildPartnerWidgets(Root);
		BuildPhoneBadge(Root);
		BuildComboCounter(Root);

		// Top right, clear of the objective line (top left) and the compass (top centre).
		ChallengePanel = WidgetTree->ConstructWidget<UChallengePanelWidget>(UChallengePanelWidget::StaticClass(), TEXT("ChallengePanelHud"));
		ChallengePanel->SetVisibility(ESlateVisibility::HitTestInvisible);
		if (UOverlaySlot* PanelSlot = Cast<UOverlaySlot>(Root->AddChild(ChallengePanel)))
		{
			PanelSlot->SetHorizontalAlignment(HAlign_Right);
			PanelSlot->SetVerticalAlignment(VAlign_Top);
			PanelSlot->SetPadding(FMargin(0.f, 48.f, 48.f, 0.f));
		}

		// Under the challenge panel's place: a crime pauses while a challenge runs, so they rarely share.
		CrimePanel = WidgetTree->ConstructWidget<UCrimePanelWidget>(UCrimePanelWidget::StaticClass(), TEXT("CrimePanelHud"));
		CrimePanel->SetVisibility(ESlateVisibility::HitTestInvisible);
		if (UOverlaySlot* CrimeSlot = Cast<UOverlaySlot>(Root->AddChild(CrimePanel)))
		{
			CrimeSlot->SetHorizontalAlignment(HAlign_Right);
			CrimeSlot->SetVerticalAlignment(VAlign_Top);
			CrimeSlot->SetPadding(FMargin(0.f, 190.f, 48.f, 0.f));
		}

		// Under the objective marker and the hotbar: the thugs' glyphs and health bars.
		ThugOverhead = WidgetTree->ConstructWidget<UHawkeyeThugOverheadWidget>(
			UHawkeyeThugOverheadWidget::StaticClass(), TEXT("ThugOverhead"));
		ThugOverhead->SetVisibility(ESlateVisibility::HitTestInvisible);
		if (UOverlaySlot* OverheadSlot = Cast<UOverlaySlot>(Root->AddChild(ThugOverhead)))
		{
			OverheadSlot->SetHorizontalAlignment(HAlign_Fill);
			OverheadSlot->SetVerticalAlignment(VAlign_Fill);
		}

		ObjectiveMarker = WidgetTree->ConstructWidget<UHawkeyeObjectiveWidget>(
			UHawkeyeObjectiveWidget::StaticClass(), TEXT("ObjectiveMarker"));
		ObjectiveMarker->SetVisibility(ESlateVisibility::HitTestInvisible);
		if (UOverlaySlot* MarkerSlot = Cast<UOverlaySlot>(Root->AddChild(ObjectiveMarker)))
		{
			MarkerSlot->SetHorizontalAlignment(HAlign_Fill);
			MarkerSlot->SetVerticalAlignment(VAlign_Fill);
		}

		// The hotbar is its own widget so it can be styled and tested on its own, but it lives
		// inside the HUD's overlay rather than being a second thing the controller manages.
		TSubclassOf<UHawkeyeHotbarWidget> HotbarClass = HotbarWidgetClass;
		if (!HotbarClass)
		{
			HotbarClass = UHawkeyeHotbarWidget::StaticClass();
		}
		Hotbar = WidgetTree->ConstructWidget<UHawkeyeHotbarWidget>(HotbarClass, TEXT("Hotbar"));
		if (UOverlaySlot* HotbarSlot = Cast<UOverlaySlot>(Root->AddChild(Hotbar)))
		{
			HotbarSlot->SetHorizontalAlignment(HAlign_Center);
			HotbarSlot->SetVerticalAlignment(VAlign_Bottom);
			HotbarSlot->SetPadding(FMargin(0.f, 0.f, 0.f, 24.f));
		}

		// Last, so the wheel draws over everything else while it is open.
		QuiverWheel = WidgetTree->ConstructWidget<UHawkeyeQuiverWheelWidget>(
			UHawkeyeQuiverWheelWidget::StaticClass(), TEXT("QuiverWheel"));
		if (UOverlaySlot* WheelSlot = Cast<UOverlaySlot>(Root->AddChild(QuiverWheel)))
		{
			WheelSlot->SetHorizontalAlignment(HAlign_Fill);
			WheelSlot->SetVerticalAlignment(VAlign_Fill);
		}
	}

	return Super::RebuildWidget();
}

void UHawkeyeHudWidget::BuildPhoneBadge(UOverlay* Root)
{
	if (!WidgetTree || !Root)
	{
		return;
	}
	UHorizontalBox* Badge = WidgetTree->ConstructWidget<UHorizontalBox>(UHorizontalBox::StaticClass(), TEXT("PhoneBadge"));
	PhoneBadge = Badge;
	if (UOverlaySlot* BadgeSlot = Cast<UOverlaySlot>(Root->AddChild(Badge)))
	{
		BadgeSlot->SetHorizontalAlignment(HAlign_Right);
		BadgeSlot->SetVerticalAlignment(VAlign_Bottom);
		BadgeSlot->SetPadding(FMargin(0.f, 0.f, 48.f, 96.f));
	}

	// The outline of a phone: a hollow rounded box, taller than wide.
	USizeBox* IconSize = WidgetTree->ConstructWidget<USizeBox>(USizeBox::StaticClass(), TEXT("PhoneIconSize"));
	IconSize->SetWidthOverride(15.f);
	IconSize->SetHeightOverride(25.f);
	PhoneIcon = WidgetTree->ConstructWidget<UBorder>(UBorder::StaticClass(), TEXT("PhoneIcon"));
	PhoneIcon->SetBrush(FSlateRoundedBoxBrush(FLinearColor::Transparent, 3.f, FLinearColor::White, 1.5f));
	IconSize->AddChild(PhoneIcon);
	if (UHorizontalBoxSlot* IconSlot = Cast<UHorizontalBoxSlot>(Badge->AddChild(IconSize)))
	{
		IconSlot->SetVerticalAlignment(VAlign_Center);
	}

	PhoneBadgeText = WidgetTree->ConstructWidget<UTextBlock>(UTextBlock::StaticClass(), TEXT("PhoneBadgeText"));
	FSlateFontInfo Font = PhoneBadgeText->GetFont();
	Font.Size = 16;
	PhoneBadgeText->SetFont(Font);
	PhoneBadgeText->SetColorAndOpacity(FSlateColor(ReticleColor));
	if (UHorizontalBoxSlot* CountSlot = Cast<UHorizontalBoxSlot>(Badge->AddChild(PhoneBadgeText)))
	{
		CountSlot->SetVerticalAlignment(VAlign_Center);
		CountSlot->SetPadding(FMargin(8.f, 0.f, 0.f, 0.f));
	}
	UpdatePhoneBadge();
}

void UHawkeyeHudWidget::BuildComboCounter(UOverlay* Root)
{
	if (!WidgetTree || !Root)
	{
		return;
	}
	ComboText = WidgetTree->ConstructWidget<UTextBlock>(UTextBlock::StaticClass(), TEXT("ComboText"));
	FSlateFontInfo Font = ComboText->GetFont();
	Font.Size = 22;
	ComboText->SetFont(Font);
	ComboText->SetColorAndOpacity(FSlateColor(ComboColor));
	ComboText->SetShadowOffset(FVector2D(1.f, 1.f));
	ComboText->SetShadowColorAndOpacity(FLinearColor(0.f, 0.f, 0.f, 0.6f));
	ComboText->SetVisibility(ESlateVisibility::HitTestInvisible);
	if (UOverlaySlot* ComboSlot = Cast<UOverlaySlot>(Root->AddChild(ComboText)))
	{
		// Right of the reticle and a little above it, where the eye already is in a fight.
		ComboSlot->SetHorizontalAlignment(HAlign_Right);
		ComboSlot->SetVerticalAlignment(VAlign_Center);
		ComboSlot->SetPadding(FMargin(0.f, 0.f, 220.f, 120.f));
	}
	UpdateComboCounter();
}

FText UHawkeyeHudWidget::FormatComboCount(int32 Count)
{
	return Count >= 2 ? FText::FromString(FString::Printf(TEXT("x%d"), Count)) : FText::GetEmpty();
}

void UHawkeyeHudWidget::UpdateComboCounter()
{
	const APlayerController* PC = GetOwningPlayer();
	const AHawkeyeCharacter* Character = PC ? Cast<AHawkeyeCharacter>(PC->GetPawn()) : nullptr;
	const int32 Count = Character ? Character->GetComboCount() : 0;
	const bool bBonus = Character && Character->IsComboBonusActive();
	if (!ComboText || (Count == ShownComboCount && bBonus == bShownComboBonus))
	{
		return;
	}
	ShownComboCount = Count;
	bShownComboBonus = bBonus;
	ComboText->SetText(FormatComboCount(Count));
	ComboText->SetColorAndOpacity(FSlateColor(bBonus ? ComboBonusColor : ComboColor));
	// The glow: a purple halo in place of the drop shadow.
	ComboText->SetShadowOffset(bBonus ? FVector2D::ZeroVector : FVector2D(1.f, 1.f));
	ComboText->SetShadowColorAndOpacity(bBonus ? FLinearColor(0.6f, 0.2f, 1.f, 0.9f) : FLinearColor(0.f, 0.f, 0.f, 0.6f));
	FSlateFontInfo Font = ComboText->GetFont();
	Font.OutlineSettings.OutlineSize = bBonus ? 2 : 0;
	Font.OutlineSettings.OutlineColor = FLinearColor(0.55f, 0.15f, 1.f, 0.85f);
	ComboText->SetFont(Font);
}

void UHawkeyeHudWidget::UpdatePhoneBadge()
{
	const UPhoneSubsystem* Phone = UPhoneSubsystem::Get(this);
	const int32 Count = Phone ? Phone->GetUnreadCount() : 0;
	if (Count == PhoneBadgeCount)
	{
		return;
	}
	PhoneBadgeCount = Count;
	if (PhoneBadgeText)
	{
		PhoneBadgeText->SetText(Count > 0 ? FText::AsNumber(Count) : FText::GetEmpty());
	}
	if (PhoneIcon)
	{
		// Dim until something is waiting, then Kate purple (the palette's).
		const FLinearColor Outline = Count > 0 ? ReticleColor : FLinearColor(1.f, 1.f, 1.f, 0.45f);
		PhoneIcon->SetBrush(FSlateRoundedBoxBrush(FLinearColor::Transparent, 3.f, Outline, 1.5f));
	}
}

void UHawkeyeHudWidget::SetQuiverWheelState(bool bOpen, int32 QuiverSlot)
{
	if (QuiverWheel)
	{
		QuiverWheel->SetWheelState(bOpen, QuiverSlot);
	}
}

void UHawkeyeHudWidget::BuildReticle(UOverlay* Root)
{
	if (!WidgetTree || !Root)
	{
		return;
	}

	if (!Reticle)
	{
		Reticle = WidgetTree->ConstructWidget<UCanvasPanel>(UCanvasPanel::StaticClass(), TEXT("Reticle"));
	}

	// The canvas fills the screen and the dot is anchored to its centre, which is the only way
	// to land on the exact centre pixel regardless of resolution.
	if (UOverlaySlot* ReticleSlot = Cast<UOverlaySlot>(Root->AddChild(Reticle)))
	{
		ReticleSlot->SetHorizontalAlignment(HAlign_Fill);
		ReticleSlot->SetVerticalAlignment(VAlign_Fill);
	}

	ReticleDot = WidgetTree->ConstructWidget<UBorder>(UBorder::StaticClass(), TEXT("ReticleDot"));
	ReticleDot->SetPadding(FMargin(0.f));
	if (UCanvasPanelSlot* DotSlot = Cast<UCanvasPanelSlot>(Reticle->AddChild(ReticleDot)))
	{
		DotSlot->SetAnchors(FAnchors(0.5f, 0.5f));
		DotSlot->SetAlignment(FVector2D(0.5f, 0.5f));
		DotSlot->SetAutoSize(false);
		DotSlot->SetPosition(FVector2D::ZeroVector);
	}

	// The spread ring: a transparent box with a round outline, sized every frame to the cone.
	FSlateBrush RingBrush;
	RingBrush.DrawAs = ESlateBrushDrawType::RoundedBox;
	RingBrush.TintColor = FSlateColor(FLinearColor::Transparent);
	RingBrush.OutlineSettings = FSlateBrushOutlineSettings(0.f, FSlateColor(ReticleColor), RingLineWidth);
	RingBrush.OutlineSettings.RoundingType = ESlateBrushRoundingType::HalfHeightRadius;
	ReticleRing = WidgetTree->ConstructWidget<UImage>(UImage::StaticClass(), TEXT("ReticleRing"));
	ReticleRing->SetBrush(RingBrush);
	if (UCanvasPanelSlot* RingSlot = Cast<UCanvasPanelSlot>(Reticle->AddChild(ReticleRing)))
	{
		RingSlot->SetAnchors(FAnchors(0.5f, 0.5f));
		RingSlot->SetAlignment(FVector2D(0.5f, 0.5f));
		RingSlot->SetAutoSize(false);
		RingSlot->SetPosition(FVector2D::ZeroVector);
	}

	// The draw bar: a dim track and a fill anchored to its left end.
	auto AddBar = [this](const TCHAR* Name, const FLinearColor& Color)
	{
		UBorder* Bar = WidgetTree->ConstructWidget<UBorder>(UBorder::StaticClass(), Name);
		Bar->SetBrush(FSlateColorBrush(FLinearColor::White));
		Bar->SetBrushColor(Color);
		Bar->SetPadding(FMargin(0.f));
		if (UCanvasPanelSlot* BarSlot = Cast<UCanvasPanelSlot>(Reticle->AddChild(Bar)))
		{
			BarSlot->SetAnchors(FAnchors(0.5f, 0.5f));
			BarSlot->SetAlignment(FVector2D(0.f, 0.5f));
			BarSlot->SetAutoSize(false);
			BarSlot->SetPosition(FVector2D(-DrawBarWidth * 0.5f, DrawBarOffset));
			BarSlot->SetSize(FVector2D(DrawBarWidth, DrawBarHeight));
		}
		return Bar;
	};
	DrawBarBack = AddBar(TEXT("DrawBarBack"), FLinearColor(0.f, 0.f, 0.f, 0.45f));
	DrawBarFill = AddBar(TEXT("DrawBarFill"), ReticleColor);

	RefreshReticle();
	RefreshDrawIndicator();
}

float UHawkeyeHudWidget::ComputeSpreadRingRadius(float SpreadDegrees, float FovDegrees, float ViewportWidth, float Distance)
{
	const float HalfFov = FMath::DegreesToRadians(FMath::Clamp(FovDegrees, 1.f, 170.f) * 0.5f);
	const float WorldRadius = Distance * FMath::Tan(FMath::DegreesToRadians(FMath::Max(SpreadDegrees, 0.f)));
	const float HalfWidthAtDistance = Distance * FMath::Tan(HalfFov);
	return HalfWidthAtDistance > 0.f ? WorldRadius / HalfWidthAtDistance * ViewportWidth * 0.5f : 0.f;
}

void UHawkeyeHudWidget::SetDrawState(bool bInDrawing, float InFraction, float InRingRadius, bool bInPerfect)
{
	bDrawing = bInDrawing;
	DrawFraction = bInDrawing ? FMath::Clamp(InFraction, 0.f, 1.f) : 0.f;
	bPerfectWindow = bInDrawing && bInPerfect;
	RingRadius = bInDrawing ? FMath::Max(InRingRadius, MinRingRadius) : 0.f;
	RefreshDrawIndicator();
}

void UHawkeyeHudWidget::RefreshDrawIndicator()
{
	const ESlateVisibility Shown = bDrawing ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed;
	const bool bFlashing = HitFlashRemaining > 0.f;
	const FLinearColor Colour = bFlashing ? HitMarkerColor : ReticleColor;
	if (ReticleRing)
	{
		// The ring is the spread while drawing, and the hit marker (a small white ring) after.
		const float Radius = bDrawing ? RingRadius : HitRingRadius;
		ReticleRing->SetVisibility(bDrawing || bFlashing ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed);
		FSlateBrush Brush = ReticleRing->GetBrush();
		Brush.OutlineSettings.Color = FSlateColor(Colour);
		ReticleRing->SetBrush(Brush);
		if (UCanvasPanelSlot* RingSlot = Cast<UCanvasPanelSlot>(ReticleRing->Slot))
		{
			RingSlot->SetSize(FVector2D(Radius * 2.f, Radius * 2.f));
		}
	}
	if (DrawBarBack)
	{
		DrawBarBack->SetVisibility(Shown);
	}
	if (DrawBarFill)
	{
		DrawBarFill->SetVisibility(bDrawing && DrawFraction > 0.f ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed);
		// Full and flashing in the perfect window: release now.
		const bool bFlashOn = bPerfectWindow && FMath::Fmod(FPlatformTime::Seconds() * 20.0, 2.0) < 1.0;
		DrawBarFill->SetBrushColor(bPerfectWindow ? (bFlashOn ? FLinearColor::White : PerfectColor) : Colour);
		if (UCanvasPanelSlot* FillSlot = Cast<UCanvasPanelSlot>(DrawBarFill->Slot))
		{
			FillSlot->SetSize(FVector2D(DrawBarWidth * DrawFraction, DrawBarHeight));
		}
	}
}

UBowComponent* UHawkeyeHudWidget::FindPawnBow() const
{
	const APlayerController* PC = GetOwningPlayer();
	const APawn* Pawn = PC ? PC->GetPawn() : nullptr;
	return Pawn ? Pawn->FindComponentByClass<UBowComponent>() : nullptr;
}

void UHawkeyeHudWidget::PollPawnDrawState(const FGeometry& MyGeometry)
{
	UBowComponent* Bow = FindPawnBow();
	if (Bow != BoundBow)
	{
		if (BoundBow)
		{
			BoundBow->OnHit.RemoveDynamic(this, &UHawkeyeHudWidget::HandleBowHit);
		}
		BoundBow = Bow;
		if (BoundBow)
		{
			BoundBow->OnHit.AddDynamic(this, &UHawkeyeHudWidget::HandleBowHit);
		}
	}

	const APlayerController* PC = GetOwningPlayer();
	const AHawkeyeCharacter* Character = PC ? Cast<AHawkeyeCharacter>(PC->GetPawn()) : nullptr;
	if (!Bow || !Bow->IsDrawing() || !Character)
	{
		SetDrawState(false, 0.f, 0.f, false);
		return;
	}
	const float Radius = ComputeSpreadRingRadius(Bow->GetCurrentSpreadDegrees(), Character->GetCurrentFOV(),
		MyGeometry.GetLocalSize().X, ReticleSpreadDistance);
	SetDrawState(true, Bow->GetDrawFraction(), Radius, Bow->IsInPerfectWindow());
}

void UHawkeyeHudWidget::HandleBowHit(AActor* /*HitActor*/, float /*Damage*/, bool /*bHeadshot*/)
{
	FlashHitMarker();
}

void UHawkeyeHudWidget::RefreshReticle()
{
	if (ReticleDot)
	{
		ReticleDot->SetBrushColor(GetReticleColor());
		if (UCanvasPanelSlot* DotSlot = Cast<UCanvasPanelSlot>(ReticleDot->Slot))
		{
			DotSlot->SetSize(FVector2D(ReticleSizePixels, ReticleSizePixels));
		}
	}

	if (Reticle)
	{
		Reticle->SetVisibility(IsReticleVisible() ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed);
	}
}

void UHawkeyeHudWidget::BuildGrappleMarker(UOverlay* Root)
{
	if (!WidgetTree || !Root)
	{
		return;
	}

	GrappleCanvas = WidgetTree->ConstructWidget<UCanvasPanel>(UCanvasPanel::StaticClass(), TEXT("GrappleCanvas"));
	if (UOverlaySlot* CanvasSlot = Cast<UOverlaySlot>(Root->AddChild(GrappleCanvas)))
	{
		CanvasSlot->SetHorizontalAlignment(HAlign_Fill);
		CanvasSlot->SetVerticalAlignment(VAlign_Fill);
	}

	// A square whose diagonal is the marker size, outlined and not filled, turned onto its point.
	const float Side = GrappleMarkerSizePixels / UE_SQRT_2;
	FSlateBrush Brush;
	Brush.DrawAs = ESlateBrushDrawType::RoundedBox;
	Brush.TintColor = FSlateColor(FLinearColor::Transparent);
	Brush.OutlineSettings = FSlateBrushOutlineSettings(0.f, FSlateColor(GrappleMarkerColor), GrappleMarkerLineWidth);
	Brush.OutlineSettings.RoundingType = ESlateBrushRoundingType::FixedRadius;
	Brush.ImageSize = FVector2D(Side, Side);

	GrappleMarker = WidgetTree->ConstructWidget<UImage>(UImage::StaticClass(), TEXT("GrappleMarker"));
	GrappleMarker->SetBrush(Brush);
	GrappleMarker->SetRenderTransformPivot(FVector2D(0.5f, 0.5f));
	GrappleMarker->SetRenderTransformAngle(45.f);
	if (UCanvasPanelSlot* MarkerSlot = Cast<UCanvasPanelSlot>(GrappleCanvas->AddChild(GrappleMarker)))
	{
		MarkerSlot->SetAnchors(FAnchors(0.f, 0.f));
		MarkerSlot->SetAlignment(FVector2D(0.5f, 0.5f));
		MarkerSlot->SetAutoSize(false);
		MarkerSlot->SetSize(FVector2D(Side, Side));
	}

	GrappleHint = WidgetTree->ConstructWidget<UTextBlock>(UTextBlock::StaticClass(), TEXT("GrappleHint"));
	GrappleHint->SetColorAndOpacity(FSlateColor(GrappleMarkerColor));
	FSlateFontInfo HintFont = GrappleHint->GetFont();
	HintFont.Size = 12;
	GrappleHint->SetFont(HintFont);
	if (UCanvasPanelSlot* HintSlot = Cast<UCanvasPanelSlot>(GrappleCanvas->AddChild(GrappleHint)))
	{
		HintSlot->SetAnchors(FAnchors(0.f, 0.f));
		HintSlot->SetAlignment(FVector2D(0.5f, 0.f));
		HintSlot->SetAutoSize(true);
	}

	// The grey one: the same diamond, dim and a touch smaller, on an anchor the zip cannot reach.
	FSlateBrush Grey = Brush;
	Grey.OutlineSettings.Color = FSlateColor(GrappleUnavailableColor);
	GrappleBlockedMarker = WidgetTree->ConstructWidget<UImage>(UImage::StaticClass(), TEXT("GrappleBlockedMarker"));
	GrappleBlockedMarker->SetBrush(Grey);
	GrappleBlockedMarker->SetRenderTransformPivot(FVector2D(0.5f, 0.5f));
	GrappleBlockedMarker->SetRenderTransformAngle(45.f);
	if (UCanvasPanelSlot* BlockedSlot = Cast<UCanvasPanelSlot>(GrappleCanvas->AddChild(GrappleBlockedMarker)))
	{
		BlockedSlot->SetAnchors(FAnchors(0.f, 0.f));
		BlockedSlot->SetAlignment(FVector2D(0.5f, 0.5f));
		BlockedSlot->SetAutoSize(false);
		BlockedSlot->SetSize(FVector2D(Side, Side) * 0.8f);
	}
	GrappleBlockedMarker->SetVisibility(ESlateVisibility::Collapsed);

	GrappleBlockedText = WidgetTree->ConstructWidget<UTextBlock>(UTextBlock::StaticClass(), TEXT("GrappleBlockedText"));
	GrappleBlockedText->SetColorAndOpacity(FSlateColor(GrappleUnavailableColor));
	FSlateFontInfo ReasonFont = GrappleBlockedText->GetFont();
	ReasonFont.Size = 10;
	GrappleBlockedText->SetFont(ReasonFont);
	if (UCanvasPanelSlot* ReasonSlot = Cast<UCanvasPanelSlot>(GrappleCanvas->AddChild(GrappleBlockedText)))
	{
		ReasonSlot->SetAnchors(FAnchors(0.f, 0.f));
		ReasonSlot->SetAlignment(FVector2D(0.5f, 0.f));
		ReasonSlot->SetAutoSize(true);
	}
	GrappleBlockedText->SetVisibility(ESlateVisibility::Collapsed);

	GrappleMarkerPainted = GrappleMarkerColor;
	GrappleCanvas->SetVisibility(ESlateVisibility::Collapsed);
}

FHawkeyeGrappleMarkerLook UHawkeyeHudWidget::GetGrappleMarkerLook(EGrappleTargetState State)
{
	FHawkeyeGrappleMarkerLook Look;
	switch (State)
	{
	case EGrappleTargetState::Ready:
		Look.bVisible = Look.bReady = Look.bHint = true;
		break;
	case EGrappleTargetState::NoArrows:
		Look.bVisible = Look.bHint = Look.bNoArrowsHint = true;
		break;
	case EGrappleTargetState::ArrowInFlight:
		Look.bVisible = true;
		break;
	default:
		break;
	}
	return Look;
}

bool UHawkeyeHudWidget::IsGrappleHintVisible() const
{
	return bGrappleMarkerVisible && GrappleLook.bHint;
}

void UHawkeyeHudWidget::UpdateGrappleMarker()
{
	APlayerController* PC = GetOwningPlayer();
	const APawn* Pawn = PC ? PC->GetPawn() : nullptr;
	const UGrappleComponent* Grapple = Pawn ? Pawn->FindComponentByClass<UGrappleComponent>() : nullptr;
	const AGrappleAnchor* Anchor = Grapple ? Grapple->GetTargetAnchor() : nullptr;
	const EGrappleTargetState State = Grapple ? Grapple->GetTargetState() : EGrappleTargetState::None;
	GrappleLook = GetGrappleMarkerLook(State);

	FVector2D Position = FVector2D::ZeroVector;
	bGrappleMarkerVisible = Anchor && GrappleLook.bVisible
		&& UWidgetLayoutLibrary::ProjectWorldLocationToWidgetPosition(PC, Anchor->GetMarkerLocation(), Position, false);
	if (bGrappleMarkerVisible)
	{
		GrappleMarkerPosition = Position;
	}
	const AGrappleAnchor* Blocked = Grapple ? Grapple->GetBlockedAnchor() : nullptr;
	FVector2D BlockedPosition = FVector2D::ZeroVector;
	bGrappleBlockedVisible = Blocked && Grapple->CanChain()
		&& UWidgetLayoutLibrary::ProjectWorldLocationToWidgetPosition(PC, Blocked->GetMarkerLocation(), BlockedPosition, false);
	GrappleHintShown = !bGrappleMarkerVisible || !GrappleLook.bHint ? FText::GetEmpty()
		: (GrappleLook.bNoArrowsHint ? GrappleNoArrowsText : ApplyGamepadHint(GrappleHintText));

	if (!GrappleCanvas || !GrappleMarker || !GrappleHint)
	{
		return;
	}
	const bool bAnything = bGrappleMarkerVisible || bGrappleBlockedVisible;
	GrappleCanvas->SetVisibility(bAnything ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed);
	if (GrappleBlockedMarker)
	{
		GrappleBlockedMarker->SetVisibility(bGrappleBlockedVisible ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed);
		if (UCanvasPanelSlot* BlockedSlot = bGrappleBlockedVisible ? Cast<UCanvasPanelSlot>(GrappleBlockedMarker->Slot) : nullptr)
		{
			BlockedSlot->SetPosition(BlockedPosition);
		}
	}
	if (GrappleBlockedText)
	{
		const bool bReason = bGrappleBlockedVisible && UGrappleComponent::IsDebugEnabled();
		GrappleBlockedText->SetVisibility(bReason ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed);
		if (bReason)
		{
			GrappleBlockedText->SetText(FText::FromString(Grapple->GetBlockedReason()));
			if (UCanvasPanelSlot* TextSlot = Cast<UCanvasPanelSlot>(GrappleBlockedText->Slot))
			{
				TextSlot->SetPosition(BlockedPosition + FVector2D(0.f, GrappleMarkerSizePixels * 0.5f + 4.f));
			}
		}
	}
	GrappleMarker->SetVisibility(bGrappleMarkerVisible ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed);
	GrappleHint->SetVisibility(IsGrappleHintVisible() ? ESlateVisibility::HitTestInvisible : ESlateVisibility::Collapsed);
	if (!bGrappleMarkerVisible)
	{
		return;
	}
	const FLinearColor Colour = GrappleLook.bReady ? GrappleMarkerColor : GrappleUnavailableColor;
	if (Colour != GrappleMarkerPainted)
	{
		GrappleMarkerPainted = Colour;
		FSlateBrush Brush = GrappleMarker->GetBrush();
		Brush.OutlineSettings.Color = FSlateColor(Colour);
		GrappleMarker->SetBrush(Brush);
		GrappleHint->SetColorAndOpacity(FSlateColor(Colour));
	}
	if (UCanvasPanelSlot* MarkerSlot = Cast<UCanvasPanelSlot>(GrappleMarker->Slot))
	{
		MarkerSlot->SetPosition(Position);
	}
	if (UCanvasPanelSlot* HintSlot = Cast<UCanvasPanelSlot>(GrappleHint->Slot))
	{
		HintSlot->SetPosition(Position + FVector2D(0.f, GrappleMarkerSizePixels * 0.5f + 4.f));
	}
	GrappleHint->SetText(GrappleHintShown);
	if (UGrappleComponent::IsDebugEnabled())
	{
		GrappleHint->SetText(FText::FromString(FString::Printf(TEXT("%s  [%s, %d arrows]"), *GrappleHintShown.ToString(),
			*UEnum::GetDisplayValueAsText(State).ToString(), Grapple->GetGrappleArrows())));
		GrappleHint->SetVisibility(ESlateVisibility::HitTestInvisible);
	}
}

FLinearColor UHawkeyeHudWidget::GetReticleColor() const
{
	return HitFlashRemaining > 0.f ? HitMarkerColor : ReticleColor;
}

